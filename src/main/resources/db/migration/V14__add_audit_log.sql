-- =====================================================================
--  V14 — audit log for moderation activity
--
--  Immutable trail so a super admin can review every moderation step:
--  who submitted a job post / script, who approved or rejected it, when,
--  and why (reject reason). Rows are insert-only.
--
--  ddl-auto=validate requires this table to match the AuditLog entity.
--  Idempotent: safe to re-run.
-- =====================================================================

CREATE TABLE IF NOT EXISTS audit_logs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action        varchar(50)  NOT NULL,
    entity_type   varchar(20)  NOT NULL,
    entity_id     bigint,
    entity_title  varchar(255),
    actor_id      bigint,
    actor_email   varchar(150),
    actor_role    varchar(20),
    owner_id      bigint,
    detail        varchar(1000),
    created_at    timestamp(6)
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity_type ON audit_logs (entity_type);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs (entity_type, entity_id);

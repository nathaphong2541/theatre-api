-- =====================================================================
--  V10 — "job posts" (องค์กรหาคนทำงาน) + promote an admin user
--
--  Organization-type profiles create recruitment posts. Each post needs admin
--  approval before it is public: status PENDING -> APPROVED/REJECTED, plus an
--  owner enable/disable switch. Public listing shows APPROVED + enabled only.
--
--  ddl-auto=validate requires this table to match the JobPost entity exactly.
--  Idempotent: safe to re-run.
-- =====================================================================

CREATE TABLE IF NOT EXISTS job_posts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by     bigint NOT NULL,
    title          varchar(200) NOT NULL,
    description    text,
    image_path     varchar(500),
    professions    jsonb NOT NULL DEFAULT '[]'::jsonb,
    work_locations jsonb NOT NULL DEFAULT '[]'::jsonb,
    experience     jsonb NOT NULL DEFAULT '[]'::jsonb,
    status         varchar(20) NOT NULL DEFAULT 'PENDING',
    enabled        boolean NOT NULL DEFAULT true,
    review_note    varchar(500),
    created_at     timestamp(6),
    updated_at     timestamp(6)
);

CREATE INDEX IF NOT EXISTS idx_job_posts_created_by ON job_posts (created_by);
CREATE INDEX IF NOT EXISTS idx_job_posts_status ON job_posts (status);


-- =====================================================================
--  V7 — add the "special skills" master list (ทักษะอื่น ๆ)
--
--  A new master-data table (mirrors experience_level / union_membership):
--  members pick a set of these on their profile, stored as a JSONB id-array
--  in profiles.special_skills, with a paired free-text field
--  profiles.special_skills_other_text for the "Other / อื่น ๆ" sentinel (999).
--
--  Because spring.jpa.hibernate.ddl-auto=validate, every new table/column
--  MUST exist in a migration or the app won't start — so this file creates
--  the table, seeds the 11 fixed skills, and adds the two profile columns.
--
--  Column shape matches BaseEntity: id (identity), created_at, updated_at,
--  record_status ('A'), del_flag ('N'). The public endpoint filters on
--  del_flag='N' AND record_status='A', so seeds set them explicitly.
--
--  Idempotent: safe to re-run.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) Master table
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS special_skill (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_th       varchar(200) NOT NULL,
    name_en       varchar(200) NOT NULL,
    description   varchar(500),
    created_at    timestamp(6),
    updated_at    timestamp(6),
    record_status varchar(1) DEFAULT 'A',
    del_flag      varchar(1) DEFAULT 'N'
);

CREATE INDEX IF NOT EXISTS idx_special_skill_name_th ON special_skill (name_th);
CREATE INDEX IF NOT EXISTS idx_special_skill_name_en ON special_skill (name_en);

